static UINT8 GfMul(UINT8 A, UINT8 B)
{
    UINT8 P = 0;
    UINTN I;

    for (I = 0; I < 8; I++) {
        if (B & 1u) {
            P = (UINT8)(P ^ A);
        }
        A = Xtime(A);
        B = (UINT8)(B >> 1);
    }
    return P;
}

static void InvSubBytes(UINT8 S[16])
{
    UINTN I;
    for (I = 0; I < 16; I++) {
        S[I] = gInvSbox[S[I]];
    }
}

static void InvShiftRows(UINT8 S[16])
{
    UINT8 T;
    T = S[13]; S[13] = S[9]; S[9] = S[5]; S[5] = S[1]; S[1] = T;
    T = S[2];  S[2] = S[10]; S[10] = T;
    T = S[6];  S[6] = S[14]; S[14] = T;
    T = S[3];  S[3] = S[7];  S[7] = S[11]; S[11] = S[15]; S[15] = T;
}

static void InvMixColumns(UINT8 S[16])
{
    UINTN C;
    for (C = 0; C < 4; C++) {
        UINT8 *Col = &S[C * 4];
        UINT8 A0 = Col[0], A1 = Col[1], A2 = Col[2], A3 = Col[3];
        Col[0] = (UINT8)(GfMul(A0, 0x0eu) ^ GfMul(A1, 0x0bu) ^ GfMul(A2, 0x0du) ^ GfMul(A3, 0x09u));
        Col[1] = (UINT8)(GfMul(A0, 0x09u) ^ GfMul(A1, 0x0eu) ^ GfMul(A2, 0x0bu) ^ GfMul(A3, 0x0du));
        Col[2] = (UINT8)(GfMul(A0, 0x0du) ^ GfMul(A1, 0x09u) ^ GfMul(A2, 0x0eu) ^ GfMul(A3, 0x0bu));
        Col[3] = (UINT8)(GfMul(A0, 0x0bu) ^ GfMul(A1, 0x0du) ^ GfMul(A2, 0x09u) ^ GfMul(A3, 0x0eu));
    }
}

int IwlAesDecrypt(const UINT8 Key[16], const UINT8 In[16], UINT8 Out[16])
{
    UINT8 Rk[176];
    UINT8 S[16];
    int R;
    UINTN I;

    if (Key == NULL || In == NULL || Out == NULL) {
        return 0;
    }
    IwlAesKeyExpand(Key, Rk);
    for (I = 0; I < 16; I++) {
        S[I] = In[I];
    }
    IwlAesAddRoundKey(S, &Rk[160]);
    InvShiftRows(S);
    InvSubBytes(S);
    for (R = 9; R >= 1; R--) {
        IwlAesAddRoundKey(S, &Rk[R * 16]);
        InvMixColumns(S);
        InvShiftRows(S);
        InvSubBytes(S);
    }
    IwlAesAddRoundKey(S, Rk);
    for (I = 0; I < 16; I++) {
        Out[I] = S[I];
    }
    return 1;
}

/*
 * RFC 3394。WPA2 M3 的密钥数据用 KEK 包了组密钥。
 * 刀 #177：旧实现明文最多 48B（密文 56）。Apple M3 常带 RSN+GTK(+IGTK) 更长 → gtk=bad。
 * 扩到 24 个 8B 块（明文 192 / 密文 200），盖住 EAPOL Key Data 实际上限。
 */
#define IWL_AES_WRAP_MAX_N  24u

int IwlAesUnwrap(const UINT8 Kek[16], const UINT8 *In, UINTN InLen,
                 UINT8 *Out, UINTN OutCap, UINTN *OutLen)
{
    UINT8 A[8];
    UINT8 R[IWL_AES_WRAP_MAX_N][8];
    UINTN N;
    UINTN K;
    int J;
    int I;

    if (Kek == NULL || In == NULL || Out == NULL || OutLen == NULL) {
        return 0;
    }
    if ((InLen & 7u) != 0 || InLen < 16u
        || InLen > 8u * (IWL_AES_WRAP_MAX_N + 1u)) {
        return 0;
    }
    N = InLen / 8u - 1u;
    if (N == 0 || N > IWL_AES_WRAP_MAX_N || N * 8u > OutCap) {
        return 0;
    }
    for (K = 0; K < 8; K++) {
        A[K] = In[K];
    }
    for (K = 0; K < N; K++) {
        UINTN B;
        for (B = 0; B < 8; B++) {
            R[K][B] = In[(K + 1u) * 8u + B];
        }
    }
    for (J = 5; J >= 0; J--) {
        for (I = (int)N; I >= 1; I--) {
            UINT8 Block[16];
            UINT8 Plain[16];
            UINT32 T = (UINT32)(N * (UINTN)J + (UINTN)I);
            for (K = 0; K < 8; K++) {
                Block[K] = A[K];
                Block[8 + K] = R[I - 1][K];
            }
            Block[4] = (UINT8)(Block[4] ^ (UINT8)(T >> 24));
            Block[5] = (UINT8)(Block[5] ^ (UINT8)(T >> 16));
            Block[6] = (UINT8)(Block[6] ^ (UINT8)(T >> 8));
            Block[7] = (UINT8)(Block[7] ^ (UINT8)T);
            if (!IwlAesDecrypt(Kek, Block, Plain)) {
                return 0;
            }
            for (K = 0; K < 8; K++) {
                A[K] = Plain[K];
                R[I - 1][K] = Plain[8 + K];
            }
        }
    }
    for (K = 0; K < 8; K++) {
        if (A[K] != 0xa6u) {
            return 0;
        }
    }
    for (K = 0; K < N; K++) {
        UINTN B;
        for (B = 0; B < 8; B++) {
            Out[K * 8u + B] = R[K][B];
        }
    }
    *OutLen = N * 8u;
    return 1;
}
